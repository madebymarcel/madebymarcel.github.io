import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const config = {
  rootSize: 16,
  minViewport: 320,
  maxViewport: 1280,
  minRatio: 1.25,
  maxRatio: 1.618,
  typeSteps: 3,
  fibonacci: [3, 5, 8, 13, 21, 34, 55, 89, 144],
  pairs: [
    { label: 'Small gap', name: 'small', min: 1, max: 2 },
    { label: 'Component gap', name: 'component', min: 2, max: 3 },
    { label: 'Stack gap', name: 'stack', min: 3, max: 4 },
    { label: 'Card padding', name: 'card', min: 3, max: 5 },
    { label: 'Page gutter', name: 'page', min: 4, max: 5 },
    { label: 'Section spacing', name: 'section', min: 5, max: 7 },
    { label: 'Hero spacing', name: 'hero', min: 6, max: 8 },
  ],
};

const round = (value) => Number(value.toFixed(6));
const rem = (pixels) => `${round(pixels / config.rootSize)}rem`;

function fluid(min, max) {
  const slope = (max - min) / (config.maxViewport - config.minViewport);
  const intercept = min - slope * config.minViewport;
  const sign = slope < 0 ? '-' : '+';
  const preferred = `${rem(intercept)} ${sign} ${round(Math.abs(slope) * 100)}vw`;
  return `clamp(${rem(Math.min(min, max))}, ${preferred}, ${rem(Math.max(min, max))})`;
}

function createStyles() {
  const fixed = config.fibonacci.map((value, index) => {
    return `  --space-${index + 1}: ${rem(value)};`;
  });
  const pairs = config.pairs.map(({ name, min, max }) => {
    const value = fluid(config.fibonacci[min], config.fibonacci[max]);
    return `  --space-fluid-${name}: ${value};`;
  });
  const type = Array.from({ length: config.typeSteps }, (_, index) => {
    const step = index + 1;
    const min = config.rootSize * config.minRatio ** step;
    const max = config.rootSize * config.maxRatio ** step;
    return `  --type-step-${step}: ${fluid(min, max)};`;
  });

  return [
    '// Generated by scripts/generate-design-scales.mjs; do not edit directly.',
    ':root {',
    ...fixed,
    '',
    ...pairs,
    '',
    ...type,
    '}',
    '',
  ].join('\n');
}

function createMetadata() {
  const rows = config.pairs.flatMap(({ label, name, min, max }) => [
    '  {',
    `    label: '${label}',`,
    `    token: '--space-fluid-${name}',`,
    `    min: ${config.fibonacci[min]},`,
    `    max: ${config.fibonacci[max]},`,
    '  },',
  ]);

  return [
    '// Generated by scripts/generate-design-scales.mjs; do not edit directly.',
    `export const FIBONACCI_SPACING = [${config.fibonacci.join(', ')}] as const;`,
    '',
    'export const FLUID_SPACING = [',
    ...rows,
    '] as const;',
    '',
  ].join('\n');
}

const outputs = [
  ['src/design-system/_scales.generated.scss', createStyles()],
  ['src/design-system/scales.generated.ts', createMetadata()],
];

for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`${path} is out of date. Run npm run design:generate.`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, content);
  }
}
